import fs from 'node:fs';
import { createHash } from 'node:crypto';

// Keep the homepage bundle reproducible from tracked sources.
// home.css 放在最后：它是首页四块内容（轮播/图片/简报/项目）的唯一权威，要盖住旧规则。
const names = ['style', 'glass', 'wheel', 'scrollbar', 'responsive', 'mobile', 'tokens', 'sky', 'renewal', 'home'];
const imports = [];
const parts = names.map(name => {
  const source = fs.readFileSync(`public/css/${name}.css`, 'utf8').replace(/\r\n/g, '\n');
  return `\n/* ${name}.css */\n` + source.replace(/@import[^;]+;/g, rule => { imports.push(rule); return ''; });
});
const bundle = '/* Generated by scripts/build-css.mjs. Edit source stylesheets. */\n' + imports.join('\n') + parts.join('\n');
fs.writeFileSync('public/css/bundle.css', bundle);
const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 10);
const indexPath = 'public/index.html';
const html = fs.readFileSync(indexPath, 'utf8')
  .replace(/css\/bundle\.css\?v=[^"']+/, `css/bundle.css?v=${hash}`)
  .replace(/<link rel="stylesheet" href="\/css\/renewal\.css[^>]*>\s*/g, '');
fs.writeFileSync(indexPath, html);
console.log(`Bundled ${names.length} stylesheets (${Math.round(Buffer.byteLength(bundle) / 1024)} KB), ${hash}`);
